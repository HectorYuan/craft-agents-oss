/**
 * 纯函数：当前层（1~5）⇒ 高亮段的索引（0..4）。
 *
 * ★ 越界/非数一律夹到有效区间（不做静默失败）⇒ 徽章永远不会「一段都不亮」。
 * ★ 缺省层 = 3（稿 `3:396`「96 · 当前 L3」）⇒ 数据异常时仍有稿面一致的读数。
 */
export function activeSegmentIndex(currentLayer: number): number {
  if (!Number.isFinite(currentLayer)) return 2
  return Math.min(Math.max(Math.trunc(currentLayer), 1), LOOP_MOTIF_SEGMENTS.length) - 1
}

export interface LoopMotifProps {
  /**
   * 当前层（1~5）—— 高亮该段。
   * ★ 缺省 3 = 稿 `3:396` 的示例（「96 · 当前 L3」）。
   */
  currentLayer?: number
  /** 尺寸档：96 / 48 / 32 / 24 为同一几何的缩放；16 = 稿 `3:418`「简化为单环」 */
  size?: 16 | 24 | 32 | 48 | 96
  className?: string
  style?: CSSProperties
}

export function LoopMotif({ currentLayer = 3, size = 96, className, style }: LoopMotifProps) {
  // ★ 16 档是**另一种画法**（单环），不是缩放 ⇒ 单独分支
  if (size === 16) {
    return (
      <svg width={16} height={16} viewBox="0 0 16 16" className={className} style={style} aria-hidden="true">
        <circle cx={8} cy={8} r={4.25} fill="none" stroke={LOOP_MOTIF_COLORS.current} strokeWidth={1.5} />
      </svg>
    )
  }

  const activeIndex = activeSegmentIndex(currentLayer)
  return (
    <svg width={size} height={size} viewBox="0 0 96 96" className={className} style={style} aria-hidden="true">
      {LOOP_MOTIF_SEGMENTS.map((seg, i) => (
        <path
          key={i}
          transform={`translate(${seg.tx} ${seg.ty})`}
          d={seg.d}
          fill={i === activeIndex ? LOOP_MOTIF_COLORS.current : LOOP_MOTIF_COLORS.track}
        />
      ))}
    </svg>
  )
}

