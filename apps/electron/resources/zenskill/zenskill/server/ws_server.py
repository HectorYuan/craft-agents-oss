class SessionManager:
    """session 管理（S4 扩展为完整 JSONL 持久化）"""

    def __init__(self, workspace_manager: WorkspaceManager):
        self._wm = workspace_manager
        self._sessions: Dict[str, dict] = {}
        self._running_tasks: Dict[str, asyncio.Task] = {}

    def list_sessions(self, workspace_id: str) -> list:
        return [
            {"id": s["id"], "name": s["name"], "status": s.get("status", "idle"),
             "permissionMode": s.get("permissionMode", "allow-all"),
             "createdAt": s.get("createdAt"), "updatedAt": s.get("updatedAt")}
            for s in self._sessions.values()
            if s.get("workspaceId") == workspace_id
        ]

    def create_session(self, workspace_id: str, name: str = "untitled",
                       permission_mode: str = "allow-all",
                       enabled_source_slugs: list = None) -> dict:
        session_id = f"{time.strftime('%y%m%d')}-{uuid.uuid4().hex[:8]}"
        session = {
            "id": session_id,
            "workspaceId": workspace_id,
            "name": name,
            "status": "idle",
            "permissionMode": permission_mode,
            "enabledSourceSlugs": enabled_source_slugs or [],
            "messages": [],
            "createdAt": int(time.time() * 1000),
            "updatedAt": int(time.time() * 1000),
        }
        self._sessions[session_id] = session

        # 记忆注入：刷新 guide.md 注入最新记忆/GTD/技能数据
        if self._event_collector is not None:
            try:
                import subprocess as _subprocess
                _subprocess.Popen(
                    [sys.executable, str(Path(__file__).parent.parent.parent / "scripts" / "update_guide.py")],
                    stdout=_subprocess.DEVNULL,
                    stderr=_subprocess.DEVNULL,
                )
            except Exception:
                pass

        return session

    def get_messages(self, session_id: str) -> list:
        session = self._sessions.get(session_id, {})
        return session.get("messages", [])

    async def send_message(self, session_id: str, message: str,
                           push_event: Callable, options: dict = None) -> bool:
        """发送消息——启动 agent loop，事件流通过 push_event 推送"""
        session = self._sessions.get(session_id)
        if not session:
            return False

        session["status"] = "streaming"
        session["updatedAt"] = int(time.time() * 1000)
        session["messages"].append({
            "role": "user", "content": message,
            "timestamp": int(time.time() * 1000),
        })

        # 事件流桥接：记录用户输入到 ZenSkill event collector
        if self._event_collector is not None:
            try:
                self._event_collector.record_user_input(
                    skill_id="craft-gui",
                    input_text=message,
                )
            except Exception:
                pass

        # 推送 user message 事件
        push_event("session:event", [{
            "type": "user_message", "sessionId": session_id,
            "message": message,
        }])

        # 启动 agent loop（异步）
        task = asyncio.ensure_future(self._run_agent(
            session_id, message, push_event, session.get("enabledSourceSlugs", [])
        ))
        self._running_tasks[session_id] = task
        return True

    async def _run_agent(self, session_id: str, message: str,
                         push_event: Callable, source_slugs: list):
        """运行 agent loop，将事件推送到 WS"""
        try:
            from ..runtime.agent.agent_loop import AgentLoop, AgentLoopConfig
            from ..runtime.agent.types import (
                TextDelta, ToolExecutionStart, ToolExecutionEnd,
                AgentEnd, MessageEnd, UserMessage, Context,
            )
            from ..runtime.agent.tools import create_default_tools, DEFAULT_SYSTEM_PROMPT

            # 构建 context
            tools = create_default_tools(".")
            context = Context(
                messages=[UserMessage(content=message)],
                system_prompt=DEFAULT_SYSTEM_PROMPT,
                tools=tools,
            )

            # 获取 LLM provider
            from ..core.llm_provider import get_llm_provider
            provider = get_llm_provider()

            from ..runtime.agent.providers import create_stream, resolve_model
            model = resolve_model(None)
            stream_fn = create_stream(model)

            config = AgentLoopConfig(
                stream=stream_fn,
                model=model,
            )

            loop = AgentLoop(config)
            async for ev in loop.run(context):
                if isinstance(ev, TextDelta):
                    push_event("session:event", [{
                        "type": "text_delta", "sessionId": session_id,
                        "delta": ev.text,
                    }])
                elif isinstance(ev, ToolExecutionStart):
                    push_event("session:event", [{
                        "type": "tool_start", "sessionId": session_id,
                        "toolName": ev.tool_name, "toolUseId": ev.tool_call_id,
                        "toolInput": ev.params,
                    }])
                    # 事件流桥接：记录工具调用到 ZenSkill event collector
                    if self._event_collector is not None:
                        try:
                            self._event_collector.record_skill_execution(
                                skill_id="craft-gui",
                                task=f"{ev.tool_name}: {json.dumps(ev.params or {}, ensure_ascii=False)[:200]}",
                                success=True,
                                duration_ms=0,
                                context={"tool_name": ev.tool_name, "tool_call_id": ev.tool_call_id},
                            )
                        except Exception:
                            pass
                elif isinstance(ev, ToolExecutionEnd):
                    push_event("session:event", [{
                        "type": "tool_result", "sessionId": session_id,
                        "toolUseId": ev.tool_call_id, "toolName": ev.tool_name,
                        "result": str(ev.result), "isError": ev.is_error,
                    }])
                elif isinstance(ev, AgentEnd):
                    push_event("session:event", [{
                        "type": "complete", "sessionId": session_id,
                    }])

            session = self._sessions.get(session_id)
            if session:
                session["status"] = "idle"

        except Exception as e:
            push_event("session:event", [{
                "type": "error", "sessionId": session_id,
                "error": str(e),
            }])
            # 事件流桥接：记录错误到 ZenSkill event collector
            if self._event_collector is not None:
                try:
                    self._event_collector.record_error(
                        skill_id="craft-gui",
                        error_msg=str(e),
                    )
                except Exception:
                    pass
            session = self._sessions.get(session_id)
            if session:
                session["status"] = "error"
        finally:
            self._running_tasks.pop(session_id, None)

    def cancel(self, session_id: str):
        task = self._running_tasks.get(session_id)
        if task and not task.done():
            task.cancel()
        session = self._sessions.get(session_id)
        if session:
            session["status"] = "idle"

    def rename(self, session_id: str, name: str):
        session = self._sessions.get(session_id)
        if session:
            session["name"] = name

    def set_permission_mode(self, session_id: str, mode: str):
        session = self._sessions.get(session_id)
        if session:
            # Craft → ZenSkill 模式映射
            mode_map = {"safe": "restricted", "ask": "plan", "allow-all": "full"}
            session["permissionMode"] = mode_map.get(mode, mode)

    def set_sources(self, session_id: str, source_slugs: list):
        session = self._sessions.get(session_id)
        if session:
            session["enabledSourceSlugs"] = source_slugs


