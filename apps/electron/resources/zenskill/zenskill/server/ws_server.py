class RPCHandler:
    """Craft WS RPC channel 分发器。

    每个 WS 连接持有一个 RPCHandler 实例。
    channel handler 签名：async (ctx, *args) -> result
    """

    def __init__(self, server: "ZenWebServer", ws: web.WebSocketResponse, fallback_token: str = None):
        self.server = server
        self.ws = ws
        self.client_id: Optional[str] = None
        self.workspace_id: Optional[str] = None
        self._fallback_token = fallback_token  # 从 cookie 中提取的 token
        self._handlers: Dict[str, Callable] = {}
        self._register_handlers()

    def _register_handlers(self):
        """注册 channel handler"""
        # 系统
        self._handlers["credentials:healthCheck"] = self._health_check
        self._handlers["system:versions"] = self._versions
        # Workspaces
        self._handlers["workspaces:get"] = self._workspaces_get
        self._handlers["workspaces:create"] = self._workspaces_create
        self._handlers["window:switchWorkspace"] = self._switch_workspace
        # Sessions
        self._handlers["sessions:get"] = self._sessions_get
        self._handlers["sessions:create"] = self._sessions_create
        self._handlers["sessions:getMessages"] = self._sessions_get_messages
        self._handlers["sessions:sendMessage"] = self._sessions_send_message
        self._handlers["sessions:cancel"] = self._sessions_cancel
        self._handlers["sessions:command"] = self._sessions_command
        # Sources
        self._handlers["sources:get"] = self._sources_get
        self._handlers["sources:create"] = self._sources_create
        self._handlers["sources:delete"] = self._sources_delete
        self._handlers["sources:getMcpTools"] = self._sources_get_mcp_tools
        # LLM connections
        self._handlers["LLM_Connection:save"] = self._llm_save
        self._handlers["LLM_Connection:setDefault"] = self._llm_set_default
        self._handlers["settings:setupLlmConnection"] = self._llm_setup
        self._handlers["settings:testLlmConnectionSetup"] = self._llm_test
        # Skills / Automations（返回空列表）
        self._handlers["skills:get"] = self._empty_list
        self._handlers["skills:list"] = self._empty_list
        self._handlers["automations:get"] = self._empty_list
        self._handlers["automations:test"] = self._empty_result
        # Onboarding（SPA 启动流程）
        self._handlers["onboarding:getAuthState"] = self._get_auth_state
        self._handlers["onboarding:validateMcp"] = self._empty_result
        self._handlers["onboarding:hasClaudeOauthState"] = self._empty_result
        self._handlers["onboarding:clearClaudeOauthState"] = self._empty_result
        self._handlers["onboarding:deferSetup"] = self._empty_result

    async def handle(self, msg: dict) -> None:
        """处理一条 WS 消息"""
        msg_type = msg.get("type")

        if msg_type == "handshake":
            await self._handle_handshake(msg)
            return

        if msg_type != "request":
            return

        channel = msg.get("channel", "")
        args = msg.get("args", [])
        msg_id = msg.get("id")

        handler = self._handlers.get(channel)
        if handler is None:
            await self._send_response(msg_id, channel, success=False,
                                      error=f"Channel not found: {channel}")
            return

        try:
            result = await handler(*args)
            await self._send_response(msg_id, channel, success=True, data=result)
        except Exception as e:
            await self._send_response(msg_id, channel, success=False, error=str(e))

    async def _handle_handshake(self, msg: dict):
        """处理握手——允许无 token（cookie 认证已在 HTTP upgrade 层完成）"""
        protocol_version = msg.get("protocolVersion", "1.0")
        token = msg.get("token")

        # 如果 handshake 消息带了 token，验证它；否则信任 HTTP 层的 cookie 认证
        if token and not self.server.verify_token(token):
            await self._send_envelope({
                "type": "handshake_ack",
                "error": {"code": "AUTH_FAILED", "message": "Invalid token"},
            })
            await self.ws.close()
            return

        self.client_id = str(uuid.uuid4())
        channels = list(self._handlers.keys())

        await self._send_envelope({
            "type": "handshake_ack",
            "clientId": self.client_id,
            "protocolVersion": "1.0",
            "registeredChannels": channels,
        })

    async def _send_response(self, msg_id: Optional[str], channel: str,
                             success: bool, data: Any = None, error: Optional[str] = None):
        payload: dict = {
            "id": msg_id,
            "type": "response",
            "channel": channel,
            "success": success,
        }
        if data is not None:
            payload["result"] = data
        if error is not None:
            payload["error"] = {"code": "INTERNAL_ERROR", "message": error}
        await self._send_envelope(payload)

    async def _send_envelope(self, envelope: dict):
        try:
            await self.ws.send_str(json.dumps(envelope, ensure_ascii=False, default=str))
        except Exception:
            pass

    def push_event(self, channel: str, args: list):
        """推送事件到客户端（fire-and-forget）"""
        asyncio.ensure_future(self._send_envelope({
            "type": "event",
            "channel": channel,
            "args": args,
        }))

