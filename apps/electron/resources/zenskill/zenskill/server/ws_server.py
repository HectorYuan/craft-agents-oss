COOKIE_NAME = "craft_session"

def _build_session_cookie(token: str) -> str:
    return f"{COOKIE_NAME}={token}; Path=/; HttpOnly; SameSite=Lax; Max-Age=86400"


def _extract_token_from_cookie(request: web.Request) -> Optional[str]:
    cookie = request.cookies.get(COOKIE_NAME)
    return cookie


