    async def _skills_get_files(self, workspace_id: str, skill_slug: str):
        """技能目录文件树（对齐 vendor SkillFile: name/type/size/children，目录优先+字母序）。"""
        def scan(dir_path: Path) -> list:
            entries = []
            try:
                for entry in sorted(dir_path.iterdir(), key=lambda e: (not e.is_dir(), e.name)):
                    if entry.name.startswith('.'):
                        continue
                    if entry.is_dir():
                        entries.append({
                            "name": entry.name, "type": "directory",
                            "children": scan(entry),
                        })
                    else:
                        entries.append({
                            "name": entry.name, "type": "file",
                            "size": entry.stat().st_size,
                        })
            except OSError:
                pass
            return entries

        skill_dir = self._skill_dir(skill_slug)
        return scan(skill_dir)

    async def _skills_delete(self, workspace_id: str, skill_slug: str):
        """删除技能目录（确认对话框在前端，后端只做防穿越校验）。"""
