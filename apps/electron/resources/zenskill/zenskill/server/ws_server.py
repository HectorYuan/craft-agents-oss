class WorkspaceManager:
    """workspace 管理（读写 ~/.zenskill/workspaces/）"""

    def __init__(self, root: Path):
        self._root = root
        self._root.mkdir(parents=True, exist_ok=True)

    def list_workspaces(self) -> list:
        workspaces = []
        for d in sorted(self._root.iterdir()):
            if d.is_dir():
                config = self._load_config(d)
                workspaces.append({
                    "id": d.name,
                    "name": config.get("name", d.name),
                    "rootPath": str(d),
                    "createdAt": config.get("createdAt"),
                })
        return workspaces

    def create_workspace(self, abs_path: str, name: str) -> dict:
        ws_id = str(uuid.uuid4())
        ws_dir = self._root / ws_id
        ws_dir.mkdir(parents=True, exist_ok=True)
        config = {"name": name, "rootPath": abs_path, "createdAt": int(time.time() * 1000)}
        (ws_dir / "config.json").write_text(json.dumps(config, indent=2))
        return {"id": ws_id, "name": name, "rootPath": abs_path}

    def _load_config(self, ws_dir: Path) -> dict:
        config_path = ws_dir / "config.json"
        if config_path.exists():
            try:
                return json.loads(config_path.read_text())
            except Exception:
                pass
        return {}

    def get_workspace_path(self, workspace_id: str) -> Optional[Path]:
        p = self._root / workspace_id
        return p if p.exists() else None


