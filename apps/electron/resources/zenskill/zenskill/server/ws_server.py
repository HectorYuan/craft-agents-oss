    def get_messages(self, session_id: str) -> dict:
        """会话消息历史。官方 GET_MESSAGES 语义：返回整个 session 对象
        （内含 messages 数组），返回裸数组会让前端 undefined.length 崩溃。

        S3：兼容读 `type`（S3 后的 vendor 形状）和 `role`（老 Python 形状）。
        """
        session = self._sessions.get(session_id, {})
        messages = []
        agent_session = self._agent_session(session_id)
        if agent_session is not None:
            for entry in agent_session.walk():
                if entry.type != "message":
                    continue
                msg = entry.data.get("message") or {}
                # S3：type 优先（vendor 形状），回退 role（老 Python 形状）
                role = msg.get("type") or msg.get("role", "")
                if role not in ("user", "assistant"):
                    continue
                content = msg.get("content", "")
                if isinstance(content, list):
                    content = "".join(
                        b.get("text", "") for b in content if isinstance(b, dict)
                    )
                if content:
                    messages.append({
                        "id": entry.id,
                        "role": role,
                        "content": content,
                        "timestamp": entry.timestamp,
                    })
        result = dict(session)
        result["messages"] = messages
        return result

    async def send_message(self, session_id: str, message: str,
                           push_event: Callable, options: dict = None) -> bool:
        """发送消息——启动 agent loop，事件流通过 push_event 推送"""
        session = self._sessions.get(session_id)
        if not session:
            return False

        session["status"] = "streaming"
        session["updatedAt"] = int(time.time() * 1000)
        session["messages"].append({
            "role": "user", "content": message,
            "timestamp": int(time.time() * 1000),
        })
        # 持久化：user 消息入 agent JSONL（assistant/toolResult 由 on_entry 记录）
        try:
            agent_session = self._agent_session(session_id)
            if agent_session is not None:
                from ..runtime.agent.types import UserMessage
                agent_session.append_message(UserMessage(content=message))
            meta = self._index.get(session_id)
            if meta is not None:
                meta["updatedAt"] = session["updatedAt"]
                self._save_index()
        except Exception:
            pass

        # 事件流桥接：记录用户输入到 ZenSkill event collector
        if self._event_collector is not None:
            try:
                self._event_collector.record_user_input(
                    skill_id="zenskill-gui",
                    input_text=message,
                )
            except Exception:
                pass

        # 推送 user message 事件
        push_event("session:event", [{
            "type": "user_message", "sessionId": session_id,
            "message": message,
        }])

        # 启动 agent loop（异步）
        task = asyncio.ensure_future(self._run_agent(
            session_id, message, push_event, session.get("enabledSourceSlugs", [])
        ))
        self._running_tasks[session_id] = task
        return True

