    async def _skills_get(self, workspace_id: str, working_directory: str = None):
        """从 ~/.agents/skills/ 加载技能列表（frontmatter 解析）。"""
        import re as _re
        skills_dir = Path.home() / ".agents" / "skills"
        result = []
        if skills_dir.is_dir():
            for d in sorted(skills_dir.iterdir()):
                sf = d / "SKILL.md"
                if not d.is_dir() or d.name.startswith('.') or not sf.exists():
                    continue
                try:
                    content = sf.read_text(encoding="utf-8")
                    meta = {}
                    fm = _re.match(r"^---\s*\n(.*?)\n---\s*\n", content, _re.DOTALL)
                    if fm:
                        try:
                            import yaml as _yaml
                            raw = _yaml.safe_load(fm.group(1))
                            if isinstance(raw, dict):
                                meta = raw
                        except Exception:
                            pass
                    result.append({
                        "slug": d.name,
                        "metadata": meta,
                        "content": content[fm.end():][:500] if fm else "",
                        "path": str(d),
                        "source": "global",
                    })
                except Exception:
                    continue
        return result

