    async def _sessions_command(self, session_id: str, command: dict):
        """sessions:command —— 对齐 vendor dto.ts SessionCommand 30 分支契约。

        S1 协议补全分类：A=真实现（setter→_index 落盘）、B=vendor 形状的显式
        失败（返回值被 GUI await 消费，形状对齐防崩）、C=轻量内存、
        D=明确 not-implemented、E=未知 type 兜底——不再静默 {"ok": True} 假成功。
        """
        sm = self.server.session_manager
        cmd_type = command.get("type")

        def _updated(ok: bool) -> dict:
            return {"updated": True} if ok else {
                "ok": False, "error": "session not found"}

        # ── A 类 · 真实现（写内存 + _index 落盘）──
        if cmd_type == "rename":
            sm.rename(session_id, command.get("name", ""))
            return {"renamed": True}
        elif cmd_type == "setPermissionMode":
            sm.set_permission_mode(session_id, command.get("mode", "allow-all"))
            return {"updated": True}
        elif cmd_type == "setSources":
            sm.set_sources(session_id, command.get("sourceSlugs", []))
            return {"updated": True}
        elif cmd_type == "setConnection":
            ok = sm.set_connection(session_id, command.get("connectionSlug"))
            if not ok:
                return {"ok": False, "error": "session or connection not found"}
            return {"updated": True}
        elif cmd_type == "setLabels":
            return _updated(sm.set_labels(session_id,
                                          command.get("labels", [])))
        elif cmd_type == "setSessionStatus":
            return _updated(sm.set_session_status(session_id,
                                                  command.get("state", "")))
        elif cmd_type == "archive":
            return _updated(sm.set_archived(session_id, True))
        elif cmd_type == "unarchive":
            return _updated(sm.set_archived(session_id, False))
        elif cmd_type == "flag":
            return _updated(sm.set_flagged(session_id, True))
        elif cmd_type == "unflag":
            return _updated(sm.set_flagged(session_id, False))
        elif cmd_type == "setThinkingLevel":
            return _updated(sm.set_thinking_level(session_id,
                                                  command.get("level", "")))
        elif cmd_type == "setKanbanColumn":
            return _updated(sm.set_kanban_column(session_id,
                                                 command.get("column")))
        elif cmd_type == "setProjectId":
            return _updated(sm.set_project_id(session_id,
                                               command.get("projectId")))
        elif cmd_type == "updateWorkingDirectory":
            return _updated(sm.set_working_directory(session_id,
                                                     command.get("dir", "")))
        elif cmd_type == "markRead":
            return _updated(sm.mark_read(session_id))
        elif cmd_type == "markUnread":
            return _updated(sm.mark_unread(session_id))

        # ── C 类 · 轻量内存（unread 状态机的活跃查看标记，不落盘）──
        elif cmd_type == "setActiveViewing":
            session = sm._sessions.get(session_id)
            if session is None:
                return {"ok": False, "error": "session not found"}
            session["activeViewingSince"] = int(time.time() * 1000)
            return {"ok": True}

        # ── B 类 · vendor 形状的显式失败（返回值被 GUI await 消费）──
        elif cmd_type in ("shareToViewer", "updateShare", "revokeShare",
                          "refreshTitle"):
            return {"success": False,
                    "error": "not supported in server mode"}
        elif cmd_type == "copyPath":
            # 对齐 vendor sessions.ts copyPath 失败形状（{success:false}）
            return {"success": False}

        # ── D 类 · 明确 not-implemented（plan/annotation 等暂缺，不假成功）──
        elif cmd_type in ("showInFinder", "setPendingPlanExecution",
                          "markCompactionComplete",
                          "markPendingPlanExecutionDispatched",
                          "clearPendingPlanExecution", "addAnnotation",
                          "removeAnnotation", "updateAnnotation"):
            return {"ok": False, "error": f"not implemented: {cmd_type}"}

        # ── E 类 · 未知 type 兜底（防未来 vendor 加新 type 时静默吞）──
        return {"ok": False,
                "error": f"unknown session command: {cmd_type}"}

