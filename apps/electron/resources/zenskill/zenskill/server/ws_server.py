    async def handle(self, msg: dict) -> None:
        """处理一条 WS 消息"""
        msg_type = msg.get("type")

        if msg_type == "handshake":
            await self._handle_handshake(msg)
            return

        if msg_type != "request":
            return

        channel = msg.get("channel", "")
        args = msg.get("args", [])
        msg_id = msg.get("id")

        handler = self._handlers.get(channel)
        if handler is None:
            await self._send_response(msg_id, channel, success=False,
                                      error=f"Channel not found: {channel}")
            return

        try:
            result = await handler(*args)
            await self._send_response(msg_id, channel, success=True, data=result)
        except Exception as e:
            await self._send_response(msg_id, channel, success=False, error=str(e))

    async def _handle_handshake(self, msg: dict):
        """处理握手——允许无 token（cookie 认证已在 HTTP upgrade 层完成）"""
        protocol_version = msg.get("protocolVersion", "1.0")
        token = msg.get("token")

        # 如果 handshake 消息带了 token，验证它；否则信任 HTTP 层的 cookie 认证
        if token and not self.server.verify_token(token):
            await self._send_envelope({
                "type": "handshake_ack",
                "error": {"code": "AUTH_FAILED", "message": "Invalid token"},
            })
            await self.ws.close()
            return

        self.client_id = str(uuid.uuid4())
        channels = list(self._handlers.keys())

        await self._send_envelope({
            "type": "handshake_ack",
            "clientId": self.client_id,
            "protocolVersion": "1.0",
            "registeredChannels": channels,
        })

    async def _send_response(self, msg_id: Optional[str], channel: str,
                             success: bool, data: Any = None, error: Optional[str] = None):
        payload: dict = {
            "id": msg_id,
            "type": "response",
            "channel": channel,
            "success": success,
        }
        if data is not None:
            payload["result"] = data
        if error is not None:
            payload["error"] = {"code": "INTERNAL_ERROR", "message": error}
        await self._send_envelope(payload)

    async def _send_envelope(self, envelope: dict):
        try:
            # 前端 codec validateEnvelopeShape 丢弃无 id 信封——所有出站
            # 信封（含 handshake_ack/event）必须带非空 id；response 已带
            # 请求方 id，其余在此兜底注入。
            if not envelope.get("id"):
                envelope["id"] = str(uuid.uuid4())
            await self.ws.send_str(json.dumps(envelope, ensure_ascii=False, default=str))
        except Exception:
            pass

    def push_event(self, channel: str, args: list):
        """推送事件到客户端（fire-and-forget）。

        信封必须带非空 id——前端 codec 的 validateEnvelopeShape 会丢弃
        无 id 信封（Wave 2 协议核查发现，此前端到端自测客户端未校验故漏过）。
        """
        asyncio.ensure_future(self._send_envelope({
            "id": str(uuid.uuid4()),
            "type": "event",
            "channel": channel,
            "args": args,
        }))

