class ZenWebServer:
    """ZenSkill WebUI server 主类"""

    def _migrate_source_slugs(self):
        """对所有 workspace 执行旧 zenskill-N slug 迁移（幂等）"""
        try:
            from ..core.source_resolver import resolve_or_migrate
            for ws_dir in self.workspace_manager._root.iterdir():
                if ws_dir.is_dir() and (ws_dir / "sources").exists():
                    resolve_or_migrate(ws_dir)
        except Exception:
            pass  # 迁移失败不阻塞启动

    def __init__(self, webui_path: Path, token: str, port: int = 9100):
        self.webui_path = webui_path
        self.token = token
        self.port = port
        self.workspace_manager = WorkspaceManager(_workspaces_root())
        # 启动时迁移旧 zenskill-N slug → canonical "zenskill"（幂等）
        self._migrate_source_slugs()
        self.session_manager = SessionManager(self.workspace_manager)
        self.source_manager = SourceManager(self.workspace_manager)
        # 进程内工具注册表单例：callMcpTool 直调（免 spawn MCP 子进程），
        # TTL 缓存与 skill 索引跨请求生效
        from ..runtime.mcp.registry import build_default_registry
        self.registry = build_default_registry()
        # 事件流桥接：桌面端 session 事件自动记录到 ZenSkill event collector
        self._event_collector = None
        # 自动化（W1.1/1.2/1.3）
        self._automation_store = None  # lazy init per workspace
        self._automation_runner = None
        try:
            from ..mirroring.event_collector import EventCollector
            self._event_collector = EventCollector()
        except Exception:
            pass
        # 桥接注入：SessionManager 的会话事件经此进入 ZenSkill 记忆生态
        self.session_manager._event_collector = self._event_collector

    def verify_token(self, token: Optional[str]) -> bool:
        return token is not None and hmac.compare_digest(token, self.token)

    def create_app(self) -> web.Application:
        app = web.Application()
        app.router.add_post("/api/auth", self._handle_auth)
        app.router.add_get("/api/config", self._handle_config)
        app.router.add_get("/api/config/workspaces", self._handle_config_workspaces)
        app.router.add_get("/ws", self._handle_ws)
        # 托管运行时（扣子编程等）存活探针：免鉴权 plain HTTP，
        # 平台健康检查不带 token，也不会升级 WS——必须在静态资源前注册
        app.router.add_get("/healthz", self._handle_healthz)
        # 静态文件（WebUI dist）——根路径根据登录状态返回不同页面
        if self.webui_path.exists():
            index_path = self.webui_path / "index.html"
            login_path = self.webui_path / "login.html"
            secret = self.token

            async def serve_index(request: web.Request) -> web.Response:
                cookie_token = request.cookies.get(COOKIE_NAME)
                # 登录态决定返回 index 还是 login——响应不可缓存，否则
                # 登录后跳转命中缓存的 login.html 造成"登录无效"假象
                headers = {"Cache-Control": "no-store"}
                if cookie_token and _verify_jwt(secret, cookie_token):
                    return web.FileResponse(index_path, headers=headers)
                if login_path.exists():
                    return web.FileResponse(login_path, headers=headers)
                return web.FileResponse(index_path, headers=headers)

            app.router.add_get("/", serve_index)
            app.router.add_static("/", str(self.webui_path), show_index=False)

        # W1.2 自动化执行器启动
        async def _on_startup(app):
            try:
                from .automation_runner import AutomationRunner
                self._automation_runner = AutomationRunner(self)
                # 默认 workspace 初始化 store
                default_ws_id = self.session_manager.default_workspace_id()
                if default_ws_id:
                    ws_path = self.workspace_manager.get_workspace_path(default_ws_id)
                    if ws_path:
                        from .automations_store import AutomationsStore
                        self._automation_store = AutomationsStore(ws_path)
                await self._automation_runner.start()
            except Exception as exc:
                import logging
                logging.getLogger("zenskill").warning("automation runner 启动失败(非致命): %s", exc)
            # W1.5 ZenLoop 后台 worker（每 5 分钟检查循环触发）
            try:
                from ..systems.zenloop.zenloop_system import ZenLoopSystem
                self._zenloop = ZenLoopSystem()
                self._zenloop.start_background()
            except Exception as exc:
                import logging
                logging.getLogger("zenskill").warning("zenloop worker 启动失败(非致命): %s", exc)
        app.on_startup.append(_on_startup)
        return app

    async def _handle_healthz(self, request: web.Request) -> web.Response:
        return web.json_response({"healthy": True, "status": "ok"})

    async def _handle_auth(self, request: web.Request) -> web.Response:
        try:
            body = await request.json()
        except Exception:
            return web.json_response({"error": "Invalid request"}, status=400)

        password = body.get("password", "")
        if not password:
            return web.json_response({"error": "Password is required"}, status=400)

        if not self.verify_token(password):
            return web.json_response({"error": "Invalid credentials"}, status=401)

        jwt_token = _create_jwt(self.token, {"sub": "webui"})
        return web.json_response(
            {"ok": True},
            headers={"Set-Cookie": _build_session_cookie(jwt_token)},
        )

    async def _handle_config(self, request: web.Request) -> web.Response:
        # wsUrl 不需要认证——SPA 在登录前就需要读取它来建立 WS 连接。
        # host 跟随请求头：写死 localhost 会命中 IPv6(::1) 解析而服务器
        # 只听 IPv4，前端 WS 超时（Wave 2 真实浏览器验收发现）。
        # protocol 跟随 X-Forwarded-Proto（Nginx 反代 HTTPS 时 scheme 仍为 http），
        # 且 WebSocket scheme 必须映射 http→ws / https→wss——前端
        # new WebSocket(wsUrl) 不接受 https:// 形态（反代 HTTPS 场景必挂）。
        proto = request.headers.get("X-Forwarded-Proto", request.scheme)
        ws_scheme = "wss" if proto == "https" else "ws"
        return web.json_response({"wsUrl": f"{ws_scheme}://{request.host}/ws"})

    async def _handle_config_workspaces(self, request: web.Request) -> web.Response:
        token = _extract_token_from_cookie(request)
        if not token or not _verify_jwt(self.token, token):
            return web.json_response({"error": "Unauthorized"}, status=401)
        return web.json_response(self.workspace_manager.list_workspaces())

    async def _handle_ws(self, request: web.Request) -> web.WebSocketResponse:
        ws = web.WebSocketResponse()
        await ws.prepare(request)

        # 从 HTTP upgrade 请求的 cookie 中提取 token（SPA 可能不在 handshake 消息中传 token）
        cookie_token = request.cookies.get(COOKIE_NAME)
        ws_auth_token = None
        if cookie_token:
            payload = _verify_jwt(self.token, cookie_token)
            if payload:
                ws_auth_token = self.token

        handler = RPCHandler(self, ws, fallback_token=ws_auth_token)

        async for msg in ws:
            if msg.type == aiohttp.WSMsgType.TEXT:
                try:
                    data = json.loads(msg.data)
                    await handler.handle(data)
                except json.JSONDecodeError:
                    pass
            elif msg.type == aiohttp.WSMsgType.ERROR:
                break

        return ws


def create_app(webui_path: Path, token: str, port: int = 9100) -> web.Application:
    """工厂函数：创建 aiohttp Application"""
    server = ZenWebServer(webui_path, token, port)
    return server.create_app()
