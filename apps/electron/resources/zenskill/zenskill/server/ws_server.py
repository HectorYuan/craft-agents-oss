    async def _sessions_send_message(self, session_id: str, message: str,
                                     attachments=None, stored_attachments=None, options=None):
        """发送消息——启动 agent loop，事件流通过 session:event 推送"""
        options = options or {}
        accepted = await self.server.session_manager.send_message(
            session_id, message, self.push_event, options
        )
        return {"accepted": accepted}

    async def _sessions_cancel(self, session_id: str, silent: bool = False):
        self.server.session_manager.cancel(session_id)
        return {"cancelled": True}

    async def _sessions_respond_to_permission(self, session_id: str, request_id: str,
                                              allowed: bool, always_allow: bool):
        """权限审批回传（前端 confirm 弹窗 → 这里 resolve pending future）"""
        fut = self.server.session_manager._pending_permissions.pop(request_id, None)
        if fut is None or fut.done():
            return False
        fut.set_result({"allowed": bool(allowed), "alwaysAllow": bool(always_allow)})
        return True

    async def _sessions_delete(self, session_id: str):
        self.server.session_manager.delete_session(session_id)
        return {"deleted": True}

    async def _session_get_model(self, session_id: str):
        """解析链：session 显式 > workspace settings > llm_config 激活态 > 探测。"""
        session = self.server.session_manager._sessions.get(session_id)
        if session is None:
            return {"model": None}
        try:
            cfg, _ = self.server.session_manager.resolve_session_model(session)
            return {"model": cfg.id if cfg else None}
        except Exception:
            return {"model": None}

    async def _session_set_model(self, session_id: str, workspace_id: str = None,
                                 model: str = None, connection: str = None):
        """session:setModel（对齐 TS settings.ts:81 四参契约）。

        model=None → 清除会话级覆盖，回退 workspace/全局解析链。
        """
        ok = self.server.session_manager.set_model(session_id, model, connection)
        if not ok:
            return {"success": False, "error": "会话不存在"}
        self.push_event("session:event", [{
            "type": "session_model_changed", "sessionId": session_id,
            "model": model,
        }])
        return {"success": True}

