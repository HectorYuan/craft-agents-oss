class SourceManager:
    """source 管理（读写 sources/{slug}/config.json）"""

    def __init__(self, workspace_manager: WorkspaceManager):
        self._wm = workspace_manager

    def list_sources(self, workspace_id: str) -> list:
        ws_path = self._wm.get_workspace_path(workspace_id)
        if not ws_path:
            return []
        sources_dir = ws_path / "sources"
        if not sources_dir.exists():
            return []
        sources = []
        for d in sorted(sources_dir.iterdir()):
            if d.is_dir():
                config_path = d / "config.json"
                if config_path.exists():
                    try:
                        config = json.loads(config_path.read_text())
                        sources.append({"config": config, "guide": None,
                                        "folderPath": str(d),
                                        "workspaceRootPath": str(ws_path),
                                        "workspaceId": workspace_id})
                    except Exception:
                        pass
        return sources

    def create_source(self, workspace_id: str, config: dict) -> dict:
        ws_path = self._wm.get_workspace_path(workspace_id)
        if not ws_path:
            raise ValueError(f"Workspace not found: {workspace_id}")

        name = config.get("name", "New Source")
        slug = name.lower().replace(" ", "-").replace("_", "-")
        slug = f"{slug}-{uuid.uuid4().hex[:4]}"

        source_dir = ws_path / "sources" / slug
        source_dir.mkdir(parents=True, exist_ok=True)

        source_config = {
            "id": f"{slug}_{uuid.uuid4().hex[:8]}",
            "name": name,
            "slug": slug,
            "enabled": config.get("enabled", True),
            "provider": config.get("provider", "custom"),
            "type": config.get("type", "mcp"),
            "createdAt": int(time.time() * 1000),
            "updatedAt": int(time.time() * 1000),
        }
        if config.get("mcp"):
            source_config["mcp"] = config["mcp"]
        if config.get("icon"):
            source_config["icon"] = config["icon"]

        (source_dir / "config.json").write_text(json.dumps(source_config, indent=2))
        (source_dir / "guide.md").write_text(f"# {name}\n\n(Add guidelines here)\n")

        return source_config

    def delete_source(self, workspace_id: str, source_slug: str):
        ws_path = self._wm.get_workspace_path(workspace_id)
        if not ws_path:
            return
        source_dir = ws_path / "sources" / source_slug
        if source_dir.exists():
            import shutil
            shutil.rmtree(source_dir)

    def get_mcp_tools(self, workspace_id: str, source_slug: str) -> list:
        """获取 source 的 MCP 工具列表（简化版：读 config.json 中的 mcp 配置）"""
        ws_path = self._wm.get_workspace_path(workspace_id)
        if not ws_path:
            return []
        config_path = ws_path / "sources" / source_slug / "config.json"
        if not config_path.exists():
            return []
        try:
            config = json.loads(config_path.read_text())
            mcp_config = config.get("mcp", {})
            if not mcp_config:
                return []
            # 简化：返回配置中的工具定义（实际应启动 MCP server 查询）
            return [{"name": "placeholder", "description": "MCP tool", "allowed": True}]
        except Exception:
            return []


async def _build_session_tools(workspace_path):
    """会话全量工具组装（与 runtime/agent/cli.py _run_task 同源）。

    此前 _run_agent 只挂 9 个基础工具，丢失了 Plan B 时代的
    MCP source（zenskill-4 的 26 工具）/ Skill 工具 / 自定义工具——
    界面 Sources 0 / Skills 0 的直接原因。

    返回 (tools, mcp_clients)；MCP 客户端须随会话存活。
    """
    from ..runtime.agent.tools import create_default_tools
    tools = list(create_default_tools("."))
    mcp_clients = []

    # 1. MCP sources：workspace 的 sources/*/config.json（type=mcp 且 enabled）
    if workspace_path is not None:
        sources_dir = Path(workspace_path) / "sources"
        if sources_dir.is_dir():
            from ..runtime.mcp.client import MCPClient
            from ..runtime.agent.cli import _wrap_mcp_tool
            for cfg_path in sorted(sources_dir.glob("*/config.json")):
                try:
                    conf = json.loads(cfg_path.read_text())
                except Exception:
                    continue
                if not conf.get("enabled") or conf.get("type") != "mcp":
                    continue
                mcp_conf = conf.get("mcp") or {}
                command = mcp_conf.get("command")
                if not command:
                    continue
                argv = [command] + list(mcp_conf.get("args") or [])
                try:
                    client = MCPClient()
                    await asyncio.wait_for(client.connect(argv), timeout=30)
                    mcp_tools = await client.list_tools()
                    for mt in mcp_tools:
                        tools.append(_wrap_mcp_tool(client, mt))
                    mcp_clients.append(client)
                except Exception:
                    continue

    # 2. 自定义工具（~/.zenskill/tools/）
    try:
        from ..runtime.agent.custom_tools import load_custom_tools
        tools.extend(load_custom_tools())
    except Exception:
        pass

    # 3. Skill → Tool（285 skills 折叠为 skill_list/skill_load）
    try:
        from ..runtime.agent.skill_tools import load_skill_tools
        tools.extend(load_skill_tools())
    except Exception:
        pass

    return tools, mcp_clients


